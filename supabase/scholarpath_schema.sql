CREATE OR REPLACE FUNCTION "public"."match_knowledge_chunks"("query_embedding" "public"."vector", "match_count" integer DEFAULT 5, "filter" "jsonb" DEFAULT '{}'::"jsonb") RETURNS TABLE("id" bigint, "document_id" "text", "title" "text", "category" "text", "content" "text", "chunk_index" integer, "metadata" "jsonb", "similarity" double precision, "source_type" "text", "source_url" "text")
    LANGUAGE "sql"
    AS $$
  select
    kc.id,
    kc.document_id,
    kd.title,
    kd.category,
    kc.content,
    kc.chunk_index,
    kc.metadata,
    1 - (kc.embedding <=> query_embedding) as similarity,
    kd.source_type,
    kd.source_url
  from knowledge_chunks kc
  join knowledge_documents kd on kd.id = kc.document_id
  where kd.status = 'active'
    and (
      not (filter ? 'category')
      or kd.category = filter->>'category'
    )
    and (
      not (filter ? 'source_type')
      or kd.source_type = filter->>'source_type'
    )
  order by kc.embedding <=> query_embedding
  limit greatest(match_count, 1);
$$;


